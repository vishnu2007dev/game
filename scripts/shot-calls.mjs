// Phone or desktop shots of a call and a task panel. node scripts/shot-calls.mjs [base] [w] [h]
import { launchBrowser } from './browser.mjs';
import { mkdirSync } from 'node:fs';
const base = process.argv[2] ?? 'http://localhost:4173/';
const w = Number(process.argv[3] ?? 390);
const h = Number(process.argv[4] ?? 844);
const tag = w < 700 ? 'phone' : 'desk';
mkdirSync('screenshots/day1', { recursive: true });
const b = await launchBrowser();
const p = await b.newPage({ viewport: { width: w, height: h }, hasTouch: w < 700 });
p.on('pageerror', (e) => console.log('PAGEERROR', e.message));
await p.addInitScript(() => localStorage.setItem('helios.onboarded', '1'));
await p.goto(`${base}?station&snap&q=low`);
await p.waitForSelector('.ob:not([hidden])', { timeout: 300000 });
await p.waitForTimeout(3000);
await p.screenshot({ path: `screenshots/day1/${tag}-list.png`, timeout: 300000 });
await p.evaluate(() => { void window.__ctx.onCall('mara'); });
await p.waitForSelector('.ch-choice', { timeout: 120000 });
await p.waitForTimeout(3000);
await p.screenshot({ path: `screenshots/day1/${tag}-call.png`, timeout: 300000 });
await p.locator('.ch-choice').first().click();
await p.waitForSelector('.ch-hang', { timeout: 120000 });
await p.locator('.ch-hang').click();
await p.waitForTimeout(1500);
const pt = await p.evaluate(() => { window.__station.showStation('dive'); return null; });
await p.waitForTimeout(4000);
const kp = await p.evaluate(() => window.__station.hotspotPoint('keypad'));
await p.mouse.click(kp.x, kp.y);
await p.waitForSelector('.tk', { timeout: 120000 });
await p.waitForTimeout(1500);
await p.screenshot({ path: `screenshots/day1/${tag}-keypad-panel.png`, timeout: 300000 });
console.log('ok', pt);
await b.close();
